class TestOCRPipeline:
    def test_ocr_on_synthetic_frames(self):
        """
        OCR integration: run Tesseract on synthetic frames,
        measure how many expected subtitles are detected.
        """
        _ensure_test_data()
        with open(EVENTS_FILE, encoding="utf-8") as f:
            events = json.load(f)

        expected_spoken = [e for e in events if e.get("expected_spoken") and e["text"]]
        if not expected_spoken:
            pytest.skip("No expected_spoken events in test data")

        try:
            from gamevoice_ru.pipeline.ocr import TesseractOCR
            ocr = TesseractOCR("ru")
            if not ocr.is_available():
                pytest.skip(f"Tesseract unavailable: {ocr.init_error}")
        except Exception as e:
            pytest.skip(f"OCR module error: {e}")

        import cv2

        recognized_count = 0
        timing_records = []

        for event in expected_spoken[:20]:  # Sample first 20 expected events
            fpath = FRAMES_DIR / event["file"]
            if not fpath.exists():
                continue
            frame = cv2.imread(str(fpath))
            if frame is None:
                continue

            # Crop subtitle area (bottom 27%)
            h, w = frame.shape[:2]
            crop = frame[int(h * 0.73):h, 0:w]

            t0 = time.perf_counter()
            text = ocr.recognize(crop)
            latency = int((time.perf_counter() - t0) * 1000)
            timing_records.append(latency)

            # Check if key words from expected text appear in OCR result
            expected = event["text"].lower()
            got = text.lower()
            # At least 40% word overlap
            exp_words = set(expected.split())
            got_words = set(got.split())
            if exp_words and len(exp_words & got_words) / len(exp_words) >= 0.4:
                recognized_count += 1

        if timing_records:
            median_ms = sorted(timing_records)[len(timing_records) // 2]
            logger.info("[Integration] Median OCR latency: %dms", median_ms)

        total = min(len(expected_spoken), 20)
        pct = recognized_count / total * 100 if total > 0 else 0
        logger.info("[Integration] OCR recognition: %d/%d (%.0f%%)", recognized_count, total, pct)

        # Lenient threshold for CI on synthetic data
        assert recognized_count / total >= 0.5, (
            f"OCR recognized only {recognized_count}/{total} ({pct:.0f}%) frames. "
            "On target hardware with real GTA VI subtitles, ≥95% is required."
        )


class TestStabilizerIntegration:
    def test_dedup_over_frame_sequence(self):
        """
        Feed a sequence of identical frames through the stabilizer.
        Only the first unique text should trigger should_speak.
        """
        from gamevoice_ru.pipeline.stabilizer import SubtitleStabilizer

        stab = SubtitleStabilizer(settle_ms=0, stability_count=1, cooldown_ms=0)
        text = "Это стабильный субтитр."
        speak_count = 0
        for _ in range(10):
            result = stab.update(text)
            if result.should_speak:
                stab.mark_spoken(result.normalized)
                speak_count += 1

        assert speak_count == 1, f"Expected 1 speak, got {speak_count}"

    def test_new_text_triggers_again(self):
        """After a different text appears, it should trigger speech."""
        from gamevoice_ru.pipeline.stabilizer import SubtitleStabilizer

        stab = SubtitleStabilizer(settle_ms=0, stability_count=1, cooldown_ms=0)
        texts = [
            "Первая реплика.",
            "Вторая реплика.",
            "Третья реплика.",
        ]
        speak_count = 0
        for text in texts:
            stab.clear()
            for _ in range(3):
                result = stab.update(text)
                if result.should_speak:
                    stab.mark_spoken(result.normalized)
                    speak_count += 1

        assert speak_count >= 2, f"Expected ≥2 speaks for distinct subtitles, got {speak_count}"


